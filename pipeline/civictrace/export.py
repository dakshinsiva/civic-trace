MARKER = ".civictrace-export"


def _write(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, separators=(",", ":"), default=_default))


def _default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return None if np.isnan(o) else float(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if pd.isna(o):
        return None
    return str(o)


def _clean(v):
    if v is None:
        return None
    if isinstance(v, float) and np.isnan(v):
        return None
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating,)):
        return None if np.isnan(v) else float(v)
    return v


def _rowdict(row, cols) -> dict:
    return {c: _clean(row[c]) for c in cols}


def load_suppressions() -> dict[str, dict[str, dict]]:
    data = yaml.safe_load((CONFIG_DIR / "suppressions.yaml").read_text()) or {}
    out: dict[str, dict[str, dict]] = {"flag": {}, "tender": {}, "supplier": {}}
    for s in data.get("suppressions") or []:
        out[s["type"]][str(s["id"])] = s
    return out


def _prepare_out(out: Path) -> None:
    if out.exists():
        if not (out / MARKER).exists() and any(out.iterdir()):
            raise RuntimeError(f"{out} exists and is not a CivicTrace export directory; refusing to overwrite")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by civictrace export — do not edit\n")


def export_all(conn: sqlite3.Connection, out: Path, include_relationships: bool = False) -> dict:
    cfg = load_config()
    sup = load_suppressions()
    _prepare_out(out)
    calls = load_calls(conn)
    if calls.empty:
        _write(out / "meta.json", {"empty": True})
        return {"calls": 0}

    calls = calls[~calls["nit_id"].astype(str).isin(sup["tender"].keys())].copy()
    geo_info = _locate_calls(calls, out)
    suppressed_suppliers = {int(k) for k in sup["supplier"]}
    docs = {
        int(r["id"]): {"url": r["url"], "sha256": r["sha256"], "fetched_at": r["fetched_at"]}
        for r in conn.execute("SELECT id, url, sha256, fetched_at FROM source_document")
    }
    buyers = {int(r["dept_id"]): dict(r) for r in conn.execute("SELECT * FROM buyer")}

    # ------------------------------------------------------------ flags
    flags = []
    for r in conn.execute("SELECT payload FROM flag"):
        f = json.loads(r["payload"])
        if f["flag_id"] in sup["flag"]:
            continue
        ctx = f.get("context") or {}
        if str(ctx.get("nit_id")) in sup["tender"]:
            continue
        sid = ctx.get("supplier_id") or f["observed"].get("supplier_id")
        if sid is not None and int(sid) in suppressed_suppliers:
            continue
        flags.append(f)
    flags_by_call: dict[int, list[dict]] = defaultdict(list)
    flags_by_supplier: dict[int, list[dict]] = defaultdict(list)
    for f in flags:
        ctx = f.get("context") or {}
        if f["subject_type"] == "tender_call":
            flags_by_call[int(ctx["nit_id"])].append(f)
        else:
            for nit in ctx.get("nit_ids") or []:
                flags_by_call[int(nit)].append(f)
        sid = ctx.get("supplier_id") or f["observed"].get("supplier_id")
        if sid is not None:
            flags_by_supplier[int(sid)].append(f)

    def flag_stub(f: dict) -> dict:
        ctx = f.get("context") or {}
        sl = ctx.get("slice") or {}
        return {
            "flag_id": f["flag_id"],
            "rule_id": f["rule_id"],
            "rule_number": f["rule_number"],
            "rule_name": f["rule_name"],
            "rule_plain_name": f.get("rule_plain_name") or f["rule_name"],
            "subject_type": f["subject_type"],
            "headline": f["headline"],
            "direction": f.get("direction"),
            "buyer": ctx.get("buyer_code") or sl.get("buyer"),
            "division": ctx.get("division") or sl.get("division"),
            "work_category": ctx.get("work_category") or sl.get("work_category"),
            "fiscal_year": sl.get("fiscal_year") or (f["period"]["label"][3:] if f["period"]["label"].startswith("FY ") else None),
            "nit_id": ctx.get("nit_id"),
            "tender_number": ctx.get("tender_number"),
            "title": ctx.get("title"),
            "supplier_id": ctx.get("supplier_id") or f["observed"].get("supplier_id"),
            "supplier_name": ctx.get("supplier_name") or f["observed"].get("supplier_name"),
            "level": sl.get("level"),
            "ecv": f["observed"].get("estimated_contract_value"),
            "partial_period": f["period"].get("partial", False),
        }

    for f in flags:
        _write(out / "flags" / f"{f['flag_id']}.json", f)
    _write(out / "flags-index.json", [flag_stub(f) for f in flags])

    # ------------------------------------------------------------ tenders
    amend = defaultdict(list)
    for r in conn.execute("SELECT * FROM amendment ORDER BY nit_id, seq"):
        amend[int(r["nit_id"])].append(
            {k: r[k] for k in ("seq", "reason", "created_at", "close_original", "close_revised", "tech_open_original", "tech_open_revised")}
        )
    bidders = defaultdict(list)
    for r in conn.execute("SELECT * FROM bidder ORDER BY nit_id, position"):
        bidders[int(r["nit_id"])].append({k: r[k] for k in ("position", "raw_name", "total_bid", "rank")})
    hist = defaultdict(list)
    for r in conn.execute("SELECT * FROM status_history ORDER BY first_observed_at"):
        hist[int(r["nit_id"])].append({"status": r["status"], "first_observed_at": r["first_observed_at"]})
    quarantine = defaultdict(list)
    for r in conn.execute("SELECT * FROM quarantine"):
        quarantine[int(r["nit_id"])].append({"reason": r["reason"], "detail": r["detail"]})

    by_process = {k: g.sort_values("call_no") for k, g in calls.groupby("process_key")}
    tender_cols = [
        "nit_id", "tender_number", "process_key", "call_no", "dept_id", "buyer_code", "buyer_name", "division",
        "work_category", "tender_type", "notice_type", "inviting_strategy", "evaluation_type", "bid_value_type",
        "tax_type", "published_by_post", "title", "ecv", "ecv_public", "sub_estimate_total", "published_at",
        "close_at_original", "close_at_final", "query_close_at", "tech_open_at", "no_of_calls", "retendered",
        "recalled", "pre_bid_meeting", "status", "award_date", "detail_state", "fy_published", "fy_decision",
        "n_price_stage_bidders", "n_corrigenda", "n_deadline_extensions",
    ]
    tender_index = []
    for _, row in calls.iterrows():
        nit = int(row["nit_id"])
        t = _rowdict(row, tender_cols)
        q = quarantine.get(nit, [])
        attribution_hold = any(x["reason"].endswith("mismatch") for x in q)
        selection = None
        if row["has_selection"] and not attribution_hold:
            sid = int(row["supplier_id"])
            withheld = sid in suppressed_suppliers
            selection = {
                "supplier_id": None if withheld else sid,
                "supplier_name": "[withheld pending review]" if withheld else row["supplier_name"],
                "bid_value": _clean(row["bid_value"]),
                "negotiated_value": _clean(row["negotiated_value"]),
                "contract_value": _clean(row["contract_value"]),
                "label": row["selection_label"],
                "bid_status": row["bid_status"],
                "bid_tax_type": row["bid_tax_type"],
            }
        sources = []
        for col, label in (
            ("detail_doc_id", "KPPP tender record (full view)"),
            ("corrigenda_doc_id", "KPPP corrigenda"),
            ("award_doc_id", "KPPP selected bid"),
            ("bidders_doc_id", "KPPP comparative statement (bidders)"),
        ):
            v = row.get(col)
            if v is not None and not pd.isna(v) and int(v) in docs:
                sources.append({"label": label, **docs[int(v)]})
        proc = by_process.get(row["process_key"])
        other_calls = (
            [
                {
                    "nit_id": int(c["nit_id"]),
                    "call_no": int(c["call_no"]),
                    "status": c["status"],
                    "published_at": c["published_at"],
                    "close_at_final": c["close_at_final"],
                    "n_price_stage_bidders": _clean(c["n_price_stage_bidders"]),
                }
                for _, c in proc.iterrows()
            ]
            if proc is not None
            else []
        )
        doc = {
            **t,
            "selection": selection,
            "bidders": bidders.get(nit, []) if not attribution_hold else [],
            "amendments": amend.get(nit, []),
            "status_history": hist.get(nit, []),
            "calls_in_process": other_calls,
            "quarantine": q,
            "sources": sources,
            "portal_url": kppp.PORTAL,
            "flags": [flag_stub(f) for f in flags_by_call.get(nit, [])],
        }
        _write(out / "tenders" / f"{nit}.json", doc)
        tender_index.append(
            {
                "nit_id": nit,
                "tender_number": t["tender_number"],
                "title": t["title"],
                "buyer": t["buyer_code"],
                "division": t["division"],
                "work_category": t["work_category"],
                "status": t["status"],
                "fy": t["fy_published"],
                "ecv": t["ecv"],
                "supplier_id": selection["supplier_id"] if selection else None,
                "supplier_name": selection["supplier_name"] if selection else None,
                "bid_value": selection["bid_value"] if selection else None,
                "n_flags": len([f for f in flags_by_call.get(nit, []) if f["subject_type"] == "tender_call"]),
            }
        )
    _write(out / "tenders-index.json", tender_index)

    # ------------------------------------------------------------ suppliers
    sel = calls[calls["has_selection"]]
    supplier_index = []
    for sid, g in sel.groupby("supplier_id"):
        sid = int(sid)
        if sid in suppressed_suppliers:
            continue
        names = [r["name"] for r in conn.execute("SELECT name FROM supplier_name WHERE supplier_id=?", (sid,))]
        by_buyer = (
            g.groupby(["buyer_code", "fy_decision"])
            .agg(selections=("nit_id", "count"), bid_value=("bid_value", "sum"))
            .reset_index()
            .to_dict("records")
        )
        doc = {
            "supplier_id": sid,
            "name": g["supplier_name"].iloc[-1],
            "names_seen": names,
            "selections": int(len(g)),
            "awarded": int((g["selection_label"] == "awarded").sum()),
            "selected_no_award": int((g["selection_label"] == "selected_no_award").sum()),
            "total_bid_value": _clean(g["bid_value"].sum()),
            "by_buyer_fy": [{k: _clean(v) for k, v in r.items()} for r in by_buyer],
            "tenders": [
                {
                    "nit_id": int(r["nit_id"]),
                    "tender_number": r["tender_number"],
                    "title": r["title"],
                    "buyer": r["buyer_code"],
                    "division": r["division"],
                    "work_category": r["work_category"],
                    "fy": r["fy_decision"],
                    "ecv": _clean(r["ecv"]),
                    "bid_value": _clean(r["bid_value"]),
                    "label": r["selection_label"],
                    "n_price_stage_bidders": _clean(r["n_price_stage_bidders"]),
                }
                for _, r in g.sort_values("decision_date", ascending=False).iterrows()
            ],
            "flags": [flag_stub(f) for f in flags_by_supplier.get(sid, [])],
        }
        _write(out / "suppliers" / f"{sid}.json", doc)
        supplier_index.append({"supplier_id": sid, "name": doc["name"], "selections": doc["selections"]})
    # Alphabetical (not ranked) — the site deliberately has no supplier leaderboard.
    supplier_index.sort(key=lambda s: (s["name"] or "").lower())
    _write(out / "suppliers-index.json", supplier_index)

    # ------------------------------------------------------------ buyers + overview
    buyer_docs = {}
    window = _windows(calls)
    for code, g in calls.groupby("buyer_code"):
        buyer_docs[code] = _buyer_doc(code, g, window, flags)
        _write(out / "buyers" / f"{code}.json", buyer_docs[code])

    rule_summary = {r["rule_id"]: dict(r) for r in conn.execute("SELECT * FROM rule_summary")}
    notices = defaultdict(lambda: defaultdict(int))
    for r in conn.execute("SELECT rule_id, kind, COUNT(*) n FROM rule_notice GROUP BY 1,2"):
        notices[r["rule_id"]][r["kind"]] = r["n"]

    detailed = calls[calls["detail_state"] == "ok"]
    call_flag_ids = {int(f["context"]["nit_id"]) for f in flags if f["subject_type"] == "tender_call"}
    base_rate = {
        "calls_with_details": int(len(detailed)),
        "calls_with_any_call_level_indicator": int(detailed["nit_id"].isin(call_flag_ids).sum()),
    }
    base_rate["share"] = round(base_rate["calls_with_any_call_level_indicator"] / base_rate["calls_with_details"], 4) if len(detailed) else None

    overview = {
        "base_rate": base_rate,
        "by_buyer": [_buyer_summary(code, d) for code, d in sorted(buyer_docs.items(), key=lambda kv: -kv[1]["totals"]["calls"])],
        "rules": [
            {
                "rule_id": rid,
                "number": rc["number"],
                "name": rc["name"],
                "plain_name": rc.get("plain_name", rc["name"]),
                "plain_question": rc.get("plain_question"),
                "plain_why": rc.get("plain_why"),
                "enabled": rc.get("enabled", True),
                "flags": int(sum(1 for f in flags if f["rule_id"] == rid)),
                "evaluated": (rule_summary.get(rid) or {}).get("evaluated"),
                "slices": (rule_summary.get(rid) or {}).get("slices"),
                "notices": dict(notices.get(rid, {})),
            }
            for rid, rc in sorted(cfg["rules"].items(), key=lambda kv: kv[1]["number"])
        ],
        "window_distribution": histogram(window["window_days"], bins=40) if len(window) else None,
        "window_quantiles": quantile_summary(window["window_days"]) if len(window) else None,
        "ratio_distribution": _ratio_dist(calls),
        "single_bidder_trend": _single_bidder_trend(calls),
        "concentration": _concentration_points(flags, calls),
        "selections_by_fy": [
            {"fy": fy, "awarded": int((g["selection_label"] == "awarded").sum()), "selected_no_award": int((g["selection_label"] == "selected_no_award").sum())}
            for fy, g in sel.groupby("fy_decision")
        ],
    }
    _write(out / "overview.json", overview)
    _write(out / "facts.json", _facts(calls, flags, suppressed_suppliers))
    _write(out / "findings.json", _findings(calls, flags, rule_summary, cfg))

    # ------------------------------------------------------------ meta / methodology / coverage
    coverage = _coverage(calls)
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    version_src = f"{len(calls)}:{len(flags)}:{calls['status_observed_at'].max()}"
    meta = {
        "generated_at": now,
        "data_version": hashlib.sha1(version_src.encode()).hexdigest()[:10],
        "pipeline_version": __version__,
        "as_of": calls["status_observed_at"].max(),
        "published_range": [calls["published_at"].min(), calls["published_at"].max()],
        "buyers": [
            {k: b[k] for k in ("dept_id", "code", "name", "family", "parent_code", "effective_from", "effective_to", "note")}
            for b in buyers.values()
            if b["code"] in set(calls["buyer_code"])
        ],
        "counts": {
            "calls": int(len(calls)),
            "processes": int(calls["process_key"].nunique()),
            "calls_with_details": int(len(detailed)),
            "selections": int(calls["has_selection"].sum()),
            "suppliers": int(sel["supplier_id"].nunique()),
            "flags": len(flags),
            "quarantined": int(calls["quarantined"].sum()),
            "suppressed": {k: len(v) for k, v in sup.items()},
        },
        "coverage": coverage,
        "rules": {rid: {k: v for k, v in rc.items()} for rid, rc in cfg["rules"].items()},
        "rule_defaults": cfg["defaults"],
        "sources": [
            {
                "name": "Karnataka Public Procurement Portal (KPPP)",
                "url": kppp.PORTAL,
                "terms": "KPPP copyright policy: material may be reproduced free of charge, accurately and with the source acknowledged.",
                "coverage": "Works tenders published from 20 May 2023 onward.",
            }
        ],
        "relationships_included": include_relationships,
        "geo": geo_info,
        "suppressions": [
            {"type": t, "id": k, "reason": v.get("reason"), "since": v.get("since")} for t, d in sup.items() for k, v in d.items()
        ],
    }
    _write(out / "meta.json", meta)

    info = {"calls": len(calls), "flags": len(flags), "suppliers": len(supplier_index), "out": str(out)}
    if include_relationships:
        info["relationships"] = _export_relationships(conn, out, set(int(s) for s in sel["supplier_id"].unique()))
    return info


RULE_BITS = {"supplier_share": 1, "single_bidder": 2, "short_window": 4, "amendments": 8, "award_ratio": 16, "concentration": 32}


def _facts(calls: pd.DataFrame, flags: list[dict], suppressed_suppliers: set[int]) -> dict:
    """Compact, dictionary-encoded columnar table for the interactive explorer.

    One row per tender call whose details were fetched (not quarantined). Strings are
    stored once in dictionaries and referenced by index to keep the file small.
    """
    df = calls[(calls["detail_state"] != "pending") & (~calls["quarantined"])].copy()
    pub = pd.to_datetime(df["published_at"], utc=True, errors="coerce")
    close = pd.to_datetime(df["close_at_original"], utc=True, errors="coerce")
    df["window"] = ((close - pub).dt.total_seconds() / 86400).round(2)
    df.loc[(df["window"] <= 0) | (df["window"] > 365), "window"] = np.nan
    df["month"] = pub.dt.tz_convert("Asia/Kolkata").dt.strftime("%Y-%m")
    bits: dict[int, int] = defaultdict(int)
    for f in flags:
        b = RULE_BITS.get(f["rule_id"], 0)
        ctx = f.get("context") or {}
        nits = [ctx["nit_id"]] if f["subject_type"] == "tender_call" else (ctx.get("nit_ids") or [])
        for n in nits:
            bits[int(n)] |= b

    def enc_nullable(series: pd.Series) -> tuple[list, list]:
        vals = [None if pd.isna(v) else str(v) for v in series]
        dictionary = sorted({v for v in vals if v is not None})
        index = {v: i for i, v in enumerate(dictionary)}
        return dictionary, [None if v is None else index[v] for v in vals]

    def enc(col: str) -> tuple[list, list[int]]:
        vals = df[col].fillna("—").astype(str)
        dictionary = sorted(vals.unique())
        index = {v: i for i, v in enumerate(dictionary)}
        return dictionary, [index[v] for v in vals]

    out: dict = {"n": int(len(df)), "rule_bits": RULE_BITS, "dict": {}, "cols": {}}
    for col, key in (("buyer_code", "buyer"), ("division", "division"), ("work_category", "category"),
                     ("fy_published", "fy"), ("month", "month"), ("tender_type", "tender_type"), ("status", "status")):
        d, idx = enc(col)
        out["dict"][key] = d
        out["cols"][key] = idx

    def numcol(col: str, digits: int = 0) -> list:
        return [None if pd.isna(v) else (round(float(v), digits) if digits else int(round(float(v)))) for v in df[col]]

    sup = [None if pd.isna(v) or int(v) in suppressed_suppliers else int(v) for v in df["supplier_id"]]
    out["cols"].update(
        {
            "nit": [int(v) for v in df["nit_id"]],
            "call_no": [int(v) for v in df["call_no"]],
            "ecv": numcol("ecv"),
            "bid": numcol("bid_value"),
            "bidders": numcol("n_price_stage_bidders"),
            "window": numcol("window", 2),
            "corr": [int(v) for v in df["n_corrigenda"]],
            "ext": [int(v) for v in df["n_deadline_extensions"]],
            "sel": [0 if pd.isna(l) else (1 if l == "awarded" else 2) for l in df["selection_label"]],
            "supplier": sup,
            "flags": [bits.get(int(n), 0) for n in df["nit_id"]],
            "ac": [None if pd.isna(v) else int(v) for v in df.get("ac_no", pd.Series([None] * len(df)))],
        }
    )
    if "ward_key" in df:
        wd, widx = enc_nullable(df["ward_key"])
        out["dict"]["ward"] = wd
        out["cols"]["ward"] = widx
    names = (
        df[df["supplier_id"].notna()].groupby("supplier_id")["supplier_name"].last().to_dict()
    )
    out["suppliers"] = {str(int(k)): v for k, v in names.items() if int(k) not in suppressed_suppliers}
    return out


def _locate_calls(calls: pd.DataFrame, out: Path) -> dict:
    """Place each call on the map (constituency area and, where named, ward) and write boundaries."""
    from .geo import ATTRIBUTION, GEO_RAW, Locator, build_geo_assets, load_wards

    if not (GEO_RAW / "wards369.kml").exists():
        calls["ac_no"] = None
        calls["ward_key"] = None
        calls["geo_method"] = "none"
        return {"available": False}
    loc = Locator(load_wards(with_geometry=False))
    placed = [loc.locate(l, t) for l, t in zip(calls["location_name"], calls["title"])]
    calls["ac_no"] = [p["ac_no"] for p in placed]
    calls["ward_key"] = [p["ward_key"] for p in placed]
    calls["geo_method"] = [p["geo_method"] for p in placed]
    assets = build_geo_assets(out / "geo")
    n = len(calls) or 1
    return {
        "available": True,
        "attribution": ATTRIBUTION,
        "assets": assets,
        "share_with_area": round(float(calls["ac_no"].notna().mean()), 4),
        "share_with_ward": round(float(calls["ward_key"].notna().mean()), 4),
        "share_zonal": round(sum(1 for p in placed if p["geo_method"] == "zonal") / n, 4),
    }


def _wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float] | None:
    if not n:
        return None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (round(max(0.0, c - h), 4), round(min(1.0, c + h), 4))


def _findings(calls: pd.DataFrame, flags: list[dict], rule_summary: dict, cfg: dict) -> dict:
    """How widespread are the warning signs? Prevalence with 95% intervals, honest about coverage.

    The detail fetch order is month-stratified and pseudo-random within each month, so the
    fetched calls are close to a random sample of all listed calls while the backfill runs.
    """
    fetched = calls[(calls["detail_state"] != "pending") & (~calls["quarantined"])]
    n_fetched, n_listed = int(len(fetched)), int(len(calls))
    call_flags: dict[int, set] = defaultdict(set)
    for f in flags:
        if f["subject_type"] == "tender_call":
            call_flags[int(f["context"]["nit_id"])].add(f["rule_id"])
    fetched_ids = set(int(x) for x in fetched["nit_id"])
    any_flag = sum(1 for n in fetched_ids if call_flags.get(n))
    multi = sum(1 for n in fetched_ids if len(call_flags.get(n, ())) >= 2)

    sel = fetched[fetched["has_selection"]]
    open_known = sel[(sel["tender_type"] == "OPEN") & sel["n_price_stage_bidders"].notna()]
    single = int((open_known["n_price_stage_bidders"] == 1).sum())
    two = int((open_known["n_price_stage_bidders"] == 2).sum())
    priced = sel[(sel["ecv"] > 0) & (sel["bid_value"] > 0)]
    ratio = priced["bid_value"] / priced["ecv"]
    at_est = int((ratio.sub(1).abs() <= 0.01).sum())
    above5 = int((ratio > 1.05).sum())
    pub = pd.to_datetime(fetched["published_at"], utc=True, errors="coerce")
    close = pd.to_datetime(fetched["close_at_original"], utc=True, errors="coerce")
    win = ((close - pub).dt.total_seconds() / 86400).dropna()
    win = win[(win > 0) & (win < 365)]
    under7 = int((win < 7).sum())
    changed3 = int((fetched["n_corrigenda"] >= 3).sum())
    status = calls["status"].value_counts().to_dict()
    awarded = int(status.get("AWARDED", 0))
    eval_done = int(status.get("EVALUATION_COMPLETED", 0))
    recalled = int(status.get("RECALLED", 0))
    retendered = int(status.get("RETENDERED", 0))

    def med_diff(rs):
        r = (rs["bid_value"] / rs["ecv"] - 1) * 100
        return round(float(r.median()), 2) if len(r) else None

    by_bidders = {
        "one": med_diff(priced[priced["n_price_stage_bidders"] == 1]),
        "two": med_diff(priced[priced["n_price_stage_bidders"] == 2]),
        "three_plus": med_diff(priced[priced["n_price_stage_bidders"] >= 3]),
        "n_one": int((priced["n_price_stage_bidders"] == 1).sum()),
        "n_two": int((priced["n_price_stage_bidders"] == 2).sum()),
        "n_three_plus": int((priced["n_price_stage_bidders"] >= 3).sum()),
    }
    # Same comparison within each type of work (controls for the kind of job).
    by_cat = []
    for cat, g in priced.groupby("work_category"):
        lo = g[g["n_price_stage_bidders"].isin([1, 2])]
        hi = g[g["n_price_stage_bidders"] >= 3]
        if len(lo) >= 10 and len(hi) >= 10:
            by_cat.append({"category": cat, "low_competition": med_diff(lo), "n_low": int(len(lo)), "three_plus": med_diff(hi), "n_three_plus": int(len(hi))})
    # Illustration (not a loss estimate): what 1–2 bidder contracts would have cost at the
    # typical 3+ bidder discount for the same type of work.
    gap, gap_base = 0.0, 0.0
    for cat, g in priced.groupby("work_category"):
        hi = g[g["n_price_stage_bidders"] >= 3]
        lo = g[g["n_price_stage_bidders"].isin([1, 2])]
        if len(hi) >= 10 and len(lo):
            r3 = float((hi["bid_value"] / hi["ecv"]).median())
            diff = lo["bid_value"] - lo["ecv"] * r3
            gap += float(diff.clip(lower=0).sum())
            gap_base += float(lo["bid_value"].sum())
    # Value at stake: winning bids where only one company competed
    single_value = float(open_known.loc[open_known["n_price_stage_bidders"] == 1, "bid_value"].sum())

    def stat(k, n):
        return {"k": int(k), "n": int(n), "share": round(k / n, 4) if n else None, "ci95": _wilson(int(k), int(n))}

    return {
        "coverage": {
            "listed_calls": n_listed,
            "fetched_calls": n_fetched,
            "fetched_share": round(n_fetched / n_listed, 4) if n_listed else None,
            "sampling": "Details are fetched month by month in a pseudo-random order within each month, so the fetched set approximates a random sample of all listed tenders.",
        },
        "any_warning_sign": stat(any_flag, n_fetched),
        "two_or_more_signs": stat(multi, n_fetched),
        "single_bidder": stat(single, len(open_known)),
        "two_bidders": stat(two, len(open_known)),
        "price_within_1pct_of_estimate": stat(at_est, len(priced)),
        "price_over_5pct_above_estimate": stat(above5, len(priced)),
        "window_under_7_days": stat(under7, len(win)),
        "changed_3_plus_times": stat(changed3, n_fetched),
        "median_window_days": round(float(win.median()), 1) if len(win) else None,
        "median_price_vs_estimate_by_bidders": by_bidders,
        "single_bidder_value": single_value,
        "price_vs_estimate_by_category": by_cat,
        "competition_gap": {"amount": round(gap, 0), "of_value": round(gap_base, 0), "share": round(gap / gap_base, 4) if gap_base else None},
        "selected_value": float(sel["bid_value"].sum()),
        "status_all_listed": {
            "awarded": awarded,
            "evaluation_completed_no_award": eval_done,
            "recalled": recalled,
            "retendered": retendered,
            "listed": n_listed,
        },
        "rules": {rid: dict(v) for rid, v in rule_summary.items()},
    }


def _windows(calls: pd.DataFrame) -> pd.DataFrame:
    df = calls[(~calls["quarantined"]) & calls["close_at_original"].notna() & calls["published_at"].notna()].copy()
    pub = pd.to_datetime(df["published_at"], utc=True, errors="coerce")
    close = pd.to_datetime(df["close_at_original"], utc=True, errors="coerce")
    df["window_days"] = (close - pub).dt.total_seconds() / 86400
    return df[(df["window_days"] > 0) & (df["window_days"] < 365)]


def _ratio_dist(calls: pd.DataFrame):
    v = calls[(~calls["quarantined"]) & calls["has_selection"] & (calls["ecv"] > 0) & (calls["bid_value"] > 0)]
    if v.empty:
        return None
    r = v["bid_value"] / v["ecv"]
    r = r[(r >= 0.2) & (r <= 5)]
    return {**histogram(r, bins=40, log=True), "quantiles": quantile_summary(r)}


def _single_bidder_trend(calls: pd.DataFrame) -> list[dict]:
    v = calls[(~calls["quarantined"]) & calls["has_selection"] & (calls["tender_type"] == "OPEN") & calls["n_price_stage_bidders"].notna()]
    out = []
    for (code, fy), g in v.groupby(["buyer_code", "fy_decision"]):
        out.append({"buyer": code, "fy": fy, "single": int((g["n_price_stage_bidders"] == 1).sum()), "known": int(len(g))})
    return out


def _concentration_points(flags: list[dict], calls: pd.DataFrame) -> list[dict]:
    pts = []
    for f in flags:
        if f["rule_id"] == "concentration":
            sl = f["context"]["slice"]
            pts.append({**sl, "hhi": f["observed"]["hhi"], "top3_share": f["observed"]["top3_share"], "n": f["observed"]["selections"], "flag_id": f["flag_id"]})
    return pts


def _buyer_doc(code: str, g: pd.DataFrame, window: pd.DataFrame, flags: list[dict]) -> dict:
    sel = g[g["has_selection"] & ~g["quarantined"]]
    w = window[window["buyer_code"] == code]
    by_fy = []
    for fy, gf in g.groupby("fy_published"):
        sf = sel[sel["fy_decision"] == fy]
        known = sf[(sf["tender_type"] == "OPEN") & sf["n_price_stage_bidders"].notna()]
        by_fy.append(
            {
                "fy": fy,
                "calls": int(len(gf)),
                "statuses": {k: int(v) for k, v in gf["status"].value_counts().items()},
                "selections": int(len(sf)),
                "single_bidder": int((known["n_price_stage_bidders"] == 1).sum()),
                "bidder_count_known": int(len(known)),
                "median_bidders": _clean(known["n_price_stage_bidders"].median()) if len(known) else None,
                "selected_value": _clean(sf["bid_value"].sum()),
            }
        )
    divisions = []
    for div, gd in g.groupby("division"):
        sd = sel[sel["division"] == div]
        divisions.append({"division": div, "calls": int(len(gd)), "selections": int(len(sd)), "suppliers": int(sd["supplier_id"].nunique())})
    bflags = [f for f in flags if (f.get("context") or {}).get("buyer_code") == code or ((f.get("context") or {}).get("slice") or {}).get("buyer") == code]
    by_rule = defaultdict(int)
    for f in bflags:
        by_rule[f["rule_id"]] += 1
    return {
        "code": code,
        "name": g["buyer_name"].iloc[0],
        "totals": {"calls": int(len(g)), "processes": int(g["process_key"].nunique()), "selections": int(len(sel)), "suppliers": int(sel["supplier_id"].nunique())},
        "by_fy": sorted(by_fy, key=lambda r: r["fy"] or ""),
        "work_categories": {k: int(v) for k, v in g["work_category"].value_counts().items()},
        "divisions": sorted(divisions, key=lambda d: -d["calls"]),
        "window_distribution": histogram(w["window_days"], bins=30) if len(w) else None,
        "window_quantiles": quantile_summary(w["window_days"]) if len(w) else None,
        "ratio_distribution": _ratio_dist(g),
        "flags_by_rule": dict(by_rule),
    }


def _buyer_summary(code: str, d: dict) -> dict:
    known = sum(r["bidder_count_known"] for r in d["by_fy"])
    single = sum(r["single_bidder"] for r in d["by_fy"])
    return {
        "code": code,
        "name": d["name"],
        **d["totals"],
        "single_bidder": single,
        "bidder_count_known": known,
        "flags_by_rule": d["flags_by_rule"],
    }


def _coverage(calls: pd.DataFrame) -> list[dict]:
    fields = {
        "ecv": "Estimated contract value",
        "published_at": "Publication date",
        "close_at_original": "Original bid deadline",
        "work_category": "Work category",
        "supplier_id": "Selected supplier (where a bid was selected)",
        "n_price_stage_bidders": "Price-stage bidder count (where a bid was selected)",
        "bid_value": "Selected bid value (where a bid was selected)",
    }
    out = []
    for code, g in calls.groupby("buyer_code"):
        sel_states = g["status"].isin(list(kppp.STATUSES_WITH_SELECTION))
        row = {
            "buyer": code,
            "calls": int(len(g)),
            "details_fetched": round(float((g["detail_state"] != "pending").mean()), 4),
            "detail_unavailable": int((g["detail_state"] == "unavailable").sum()),
            "first_published": g["published_at"].min(),
            "last_published": g["published_at"].max(),
            "fields": {},
        }
        for f, label in fields.items():
            base = g[sel_states & (g["detail_state"] != "pending")] if f in ("supplier_id", "n_price_stage_bidders", "bid_value") else g[g["detail_state"] != "pending"]
            if f == "work_category":
                present = (base[f] != "Unspecified").mean() if len(base) else 0
            else:
                present = base[f].notna().mean() if len(base) else 0
            row["fields"][f] = {"label": label, "completeness": round(float(present), 4), "n": int(len(base))}
        out.append(row)
    return out


